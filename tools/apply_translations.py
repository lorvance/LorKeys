base_res_dir = r"C:\Users\Lorvance\Desktop\lorkeys_1_48_8\app\src\main\res"

for lang, items in translations.items():
    folder_name = "values" if lang == "" else f"values-{lang}"
    xml_path = os.path.join(base_res_dir, folder_name, "strings.xml")
    if not os.path.exists(xml_path):
        print(f"Skipping {xml_path} (does not exist)")
        continue
    
    with open(xml_path, "r", encoding="utf-8") as f:
        content = f.read()

    modified = False
    for key, val in items.items():
        escaped_val = re.sub(r"(?<!\\)'", r"\'", val)
        pattern = rf'<string name="{key}">.*?</string>'
        tag_str = f'<string name="{key}">{escaped_val}</string>'
        if re.search(pattern, content):
            # Update if different
            new_content = re.sub(pattern, tag_str, content)
            if new_content != content:
                content = new_content
                modified = True
        else:
            # Insert before </resources>
            idx = content.rfind("</resources>")
            if idx != -1:
                content = content[:idx] + f"    {tag_str}\n" + content[idx:]
                modified = True
    
    if modified:
        with open(xml_path, "w", encoding="utf-8") as f:
            f.write(content)
        print(f"Updated {folder_name}/strings.xml")
    else:
        print(f"No changes needed for {folder_name}/strings.xml")
